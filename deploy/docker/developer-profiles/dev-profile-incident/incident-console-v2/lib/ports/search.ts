// EvidenceSearchRepository (MVP2): the console searches Supabase directly.
// Keyword-only for now (Postgres full-text over item names and descriptions);
// queryEmbedding is optional so an embedding model can be added later, and it
// must then be the model and dimension that embedded evidence_crops.embedding.
// The adapter follows PR 126's evidence_crops / query_results tables.

import type { RunKey } from '@/lib/ports/common';

export type EvidenceItemType = 'entity' | 'instrument' | 'asset';

export interface EvidenceCropItem {
  /** incidents.incident_id, which equals videos.id. */
  incidentId: string;
  modelRunId: string;
  itemType: EvidenceItemType;
  itemId: string;
  itemName: string;
  description: string;
  threatLevel: number | null;
  holderEntityId: string | null;
  timestampSeconds: number;
  /** [ymin, xmin, ymax, xmax] normalised to 0-1000, detector-produced; null when there is none. */
  boundingBox: [number, number, number, number] | null;
  /** R2 key of the crop image. It is signed server-side; a raw key never reaches the browser. */
  imageKey: string;
  /** Relevance score on search hits (a text rank in keyword mode). */
  similarityScore?: number;
}

export interface SearchEvidenceParams {
  /** Required: keyword search and the audit record both use it. */
  queryText: string;
  /** Absent in keyword mode. */
  queryEmbedding?: number[];
  topK?: number;
  minSimilarity?: number;
  alpha?: number;
  itemTypes?: EvidenceItemType[];
  incidentTypes?: string[];
  minSeverity?: number;
  maxSeverity?: number;
}

export interface SearchQueryRecord {
  queryId: string;
  queryText: string;
  submittedAt: string;
  results: Array<{ resultId: string; rank: number; similarityScore: number; item: EvidenceCropItem; feedback: 'helpful' | 'unhelpful' | null }>;
}

export interface EvidenceSearchRepository {
  searchEvidenceItems(params: SearchEvidenceParams): Promise<Array<EvidenceCropItem & { evidenceCropId: string; similarityScore: number }>>;
  getEvidenceCrops(key: RunKey): Promise<EvidenceCropItem[]>;
  /** Writes one query and its ranked results. Ids are generated by the caller; insert-only. */
  recordQuery(query: {
    queryId: string;
    queryText: string;
    queryEmbedding?: number[];
    results: Array<{ resultId: string; evidenceCropId: string; rank: number; similarityScore: number }>;
  }): Promise<void>;
  /** Updates only the feedback columns of the result row matched by resultId and queryId. */
  saveFeedback(params: { resultId: string; queryId: string; feedback: 'helpful' | 'unhelpful'; notes?: string }): Promise<void>;
  getQueryHistory(params?: { limit?: number }): Promise<SearchQueryRecord[]>;
}
