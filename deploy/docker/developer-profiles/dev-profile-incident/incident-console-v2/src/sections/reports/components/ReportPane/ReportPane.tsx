'use client';

import type { ReactNode } from 'react';

import { EvidenceFrame } from '@/sections/evidence/components/EvidenceFrame';
import { RunDetailsPanel } from '@/sections/reports/components/ReportRunDetails';
import { timestampWithinVideo } from '@/modules/contract/domain/video-bounds';
import { formatClock } from '@/modules/reports/domain/normalize';
import { reportHeading, type ReportView, type StructuredEntity, type StructuredInstrument } from '@/modules/reports/domain/report-view';
import { formatTimestamp } from '@/lib/time';

function severityStyle(level: number | null): string {
  if (level !== null && level >= 4) return 'bg-[#ffe8df] text-[#9b3518]';
  if (level === 3) return 'bg-[#fff1c7] text-[#765300]';
  return 'bg-signal/15 text-moss';
}

const capitalize = (value: string | null) => (value ? value[0].toUpperCase() + value.slice(1) : 'Unclassified');

function Row({ label, children }: { label: string; children: ReactNode }) {
  return <div className="grid gap-1 border-b border-ink/10 py-3 sm:grid-cols-[8rem_1fr] sm:gap-6"><dt className="pt-0.5 font-mono text-[10.5px] font-bold uppercase tracking-[0.14em] text-ink/45">{label}</dt><dd className="m-0 text-sm leading-6 text-ink/80">{children}</dd></div>;
}

/** The scrolling part of View mode: the version, its report fields, its evidence grouped by holder, and the model's own output. */
export function ReportPane({ report, playerDuration, onSeek }: { report: ReportView; playerDuration: number | null; onSeek: (seconds: number) => void }) {
  const { structured, modelOutput, run, differences, revision } = report;
  const { incident } = structured;
  const windowEdited = differences.fields.includes('incident window');
  const original = modelOutput?.original;
  const heldBy = (entityId: string) => structured.instruments.filter((instrument) => instrument.entityId === entityId);
  const heldIds = new Set(structured.entities.flatMap((entity) => heldBy(entity.entityId).map((instrument) => instrument.instrumentId)));
  const unheld = structured.instruments.filter((instrument) => !heldIds.has(instrument.instrumentId));
  const holderTitle = new Map(structured.entities.map((entity) => [entity.entityId, `${entity.entityId} · ${entity.label || entity.type}`]));
  const itemCount = structured.entities.length + structured.instruments.length + structured.assets.length;

  return (
    <div className="px-5 pb-6 sm:px-8">
      <section className="mt-5 rounded-2xl bg-[#eef2e9] p-4" data-testid="version-summary">
        <p className="flex flex-wrap items-center gap-2 text-sm" data-testid="revision-label">
          <b>v{revision.revisionNo}</b>
          <span className="rounded-full bg-white px-2 py-0.5 text-[11px] font-semibold text-ink/60">{revision.kind === 'human' ? 'Human' : 'AI'}</span>
          {revision.kind === 'ai' && <span className="text-ink/60">{run.model}</span>}
          {report.official.isOfficial && <span className="rounded-full bg-[#fff1c7] px-2 py-0.5 text-[11px] font-bold text-[#765300]" data-testid="official-status">★ Official</span>}
        </p>
        <p className="mt-1 text-xs text-ink/55">{formatTimestamp(revision.createdAt, 'time unknown')}{revision.note ? ` · ${revision.note}` : ''}</p>
        {run.status === 'valid_after_structural_repair' && <p className="mt-2 inline-block rounded-full bg-[#fff1c7] px-3 py-1 text-xs font-semibold text-[#765300]" data-testid="contract-repair-applied">Contract repair applied (IDs only)</p>}
        {run.notesKind === 'legacy' && <p className="mt-2 text-xs text-ink/55">Earlier prompt version</p>}
      </section>

      <h3 className="mt-6 font-mono text-[10.5px] font-bold uppercase tracking-[0.14em] text-ink/45">Report fields</h3>
      <dl className="m-0">
        <Row label="Title">{reportHeading(report)}{modelOutput?.title && <span className="mt-0.5 block text-xs text-ink/40">Title generated by the model{differences.fields.length ? ' (before reviewer edits)' : ''}</span>}</Row>
        <Row label="Incident type">{capitalize(incident.type)}{modelOutput?.location ? ` · ${modelOutput.location}` : ''}
          {differences.type && <span className="mt-0.5 block text-xs font-semibold text-clay" data-testid="type-edited">Model classified this as {differences.type.model}; reviewer set {differences.type.current}.</span>}
        </Row>
        <Row label="Severity"><span className={`rounded-full px-3 py-0.5 text-xs font-bold ${severityStyle(incident.severityLevel)}`}>{incident.severityLevel ?? '—'}/5</span>
          {differences.severity && <span className="mt-1 block text-xs font-semibold text-clay" data-testid="severity-edited">Model assessed severity {differences.severity.model}/5; reviewer set {differences.severity.current}/5. The rationale below explains the model&apos;s assessment, not the reviewer&apos;s.</span>}
        </Row>
        {incident.confidenceScore !== null && <Row label="Confidence">{Math.round(incident.confidenceScore * 100)}%</Row>}
        <Row label="Time range">
          {incident.startSeconds !== null ? (
            <button className="rounded-full border border-ink/10 px-3 py-0.5 font-mono text-xs font-bold text-moss hover:bg-moss/5" onClick={() => onSeek(incident.startSeconds!)} type="button">{formatClock(incident.startSeconds)}{incident.endSeconds !== null ? `–${formatClock(incident.endSeconds)}` : ''}</button>
          ) : 'Not recorded'}
          {windowEdited && original && original.startSeconds !== null && original.endSeconds !== null && <span className="ml-3 text-xs font-semibold text-clay" data-testid="window-edited">reviewer-set; model window {formatClock(original.startSeconds)}–{formatClock(original.endSeconds)}</span>}
        </Row>
        <Row label="Summary"><span className="whitespace-pre-wrap">{incident.description ?? 'No summary was recorded.'}</span></Row>
        <Row label="Severity rationale"><span className="text-ink/60">{modelOutput?.severityReason ?? 'No model rationale was retained for this run.'}</span>
          {differences.severity && <span className="mt-0.5 block text-xs text-ink/40">For model severity {differences.severity.model}/5</span>}
        </Row>
      </dl>
      {differences.fields.length > 0 && <p className="mt-3 inline-block rounded-full bg-canvas px-3 py-1 text-xs font-semibold text-clay" data-testid="reviewer-edited">Reviewer-edited after generation: {differences.fields.join(', ')}</p>}

      <h3 className="mt-7 font-mono text-[10.5px] font-bold uppercase tracking-[0.14em] text-ink/45">Evidence items · {itemCount}</h3>
      {itemCount === 0 ? <p className="mt-2 text-sm italic text-ink/40" data-testid="evidence-empty">This version has no evidence items.</p> : (
        <div className="mt-2 space-y-4" data-testid="evidence-grid">
          {structured.entities.map((entity) => (
            <div className="grid gap-3 sm:grid-cols-[6rem_1fr]" data-holder={entity.entityId} key={entity.entityId}>
              <span className="font-mono text-[10.5px] font-bold uppercase tracking-wider text-ink/40">Entity</span>
              <div className="flex flex-wrap gap-3">
                <EntityCard entity={entity} holds={heldBy(entity.entityId).map((instrument) => instrument.name)} onSeek={onSeek} />
                {heldBy(entity.entityId).map((instrument) => <InstrumentCard holder={holderTitle.get(entity.entityId)} instrument={instrument} key={instrument.instrumentId} onSeek={onSeek} />)}
              </div>
            </div>
          ))}
          {unheld.length > 0 && (
            <div className="grid gap-3 sm:grid-cols-[6rem_1fr]" data-holder="unknown">
              <span className="font-mono text-[10.5px] font-bold uppercase tracking-wider text-ink/40">Holder unknown</span>
              <div className="flex flex-wrap gap-3">{unheld.map((instrument) => <InstrumentCard instrument={instrument} key={instrument.instrumentId} onSeek={onSeek} />)}</div>
            </div>
          )}
          {structured.assets.length > 0 && (
            <div className="grid gap-3 sm:grid-cols-[6rem_1fr]" data-holder="assets">
              <span className="font-mono text-[10.5px] font-bold uppercase tracking-wider text-ink/40">Assets</span>
              <div className="flex flex-wrap gap-3">
                {structured.assets.map((asset) => (
                  <Card evidence={asset.evidence} key={asset.assetId} kind="asset" onSeek={onSeek} seconds={asset.timestampSeconds} title={asset.name}>
                    <p className="text-ink/60">{asset.description}</p>
                  </Card>
                ))}
              </div>
            </div>
          )}
        </div>
      )}

      <ModelSection title="Model event timeline" source={modelOutput?.source}>
        {windowEdited && original && original.startSeconds !== null && original.endSeconds !== null && (
          <p className="mb-2 text-[11px] text-clay">Event times are the model&apos;s, relative to its original window {formatClock(original.startSeconds)}–{formatClock(original.endSeconds)}.</p>
        )}
        {modelOutput && !modelOutput.timelineCheck.consistentWithWindow && (
          <p className="mb-2 rounded-xl border border-[#e8d49a] bg-[#fffaf0] p-3 text-xs leading-5 text-[#765300]" data-testid="timeline-inconsistent">
            Model-generated timeline, not consistent with the detected incident window
            {original && original.startSeconds !== null && original.endSeconds !== null ? ` (${formatClock(original.startSeconds)}–${formatClock(original.endSeconds)})` : ''}.
            {' '}Events outside the window are the model&apos;s context, not incident timestamps. The timeline is not scored and does not affect the report&apos;s validity.
          </p>
        )}
        {modelOutput?.timeline.length ? (
          <ol className="space-y-2">
            {modelOutput.timeline.map((event, index) => {
              const clock = `${formatClock(event.startSeconds)}${event.endSeconds !== null && event.endSeconds !== event.startSeconds ? `–${formatClock(event.endSeconds)}` : ''}`;
              const outsideWindow = event.insideWindow === false;
              const seekable = event.seekable !== false && (playerDuration === null || timestampWithinVideo(event.startSeconds, playerDuration));
              const tags = (
                <>
                  {outsideWindow && <span className="rounded-full bg-ink/5 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-ink/50" data-testid="event-outside-window">outside incident window</span>}
                  {!seekable && <span className="rounded-full bg-[#ffe8df] px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-[#9b3518]" data-testid="event-outside-video">outside the video</span>}
                </>
              );
              return (
                <li key={`${event.startSeconds}-${index}`}>
                  {seekable ? (
                    <button aria-label={`Play video from ${formatClock(event.startSeconds)}: ${event.description}`} className={`group flex w-full gap-4 rounded-xl border p-3 text-left transition hover:border-moss/30 hover:bg-moss/5 focus:outline-none focus:ring-2 focus:ring-signal ${outsideWindow ? 'border-dashed border-ink/15' : 'border-ink/10'}`} onClick={() => onSeek(event.startSeconds)} type="button">
                      <span className={`whitespace-nowrap font-mono text-xs font-bold ${outsideWindow ? 'text-ink/45' : 'text-moss'}`}>{clock}</span>
                      <span className={`text-sm leading-5 ${outsideWindow ? 'text-ink/55' : 'text-ink/70'}`}>{event.description} {tags}</span>
                    </button>
                  ) : (
                    <div className="flex w-full gap-4 rounded-xl border border-dashed border-ink/15 p-3 text-left" data-testid="event-not-seekable">
                      <span className="whitespace-nowrap font-mono text-xs font-bold text-ink/40">{clock}</span>
                      <span className="text-sm leading-5 text-ink/50">{event.description} {tags}</span>
                    </div>
                  )}
                </li>
              );
            })}
          </ol>
        ) : <p className="rounded-xl border border-dashed border-ink/15 p-4 text-sm text-ink/45">{modelOutput ? 'The model returned no timestamped events.' : 'The original model output was not retained for this run.'}</p>}
      </ModelSection>

      {modelOutput && modelOutput.uncertainties.length > 0 && (
        <ModelSection title="Model-reported uncertainties" source={modelOutput.source}>
          <ul className="space-y-2 text-sm leading-5 text-ink/65">{modelOutput.uncertainties.map((item, index) => <li className="border-l-2 border-clay/40 pl-3" key={`${item}-${index}`}>{item}</li>)}</ul>
        </ModelSection>
      )}

      <div className="-mx-5 mt-6 sm:-mx-8"><RunDetailsPanel report={report} /></div>
    </div>
  );
}

function ModelSection({ title, source, children }: { title: string; source?: 'contract' | 'legacy'; children: ReactNode }) {
  return (
    <section className="mt-7">
      <h3 className="font-mono text-[10.5px] font-bold uppercase tracking-[0.14em] text-ink/45">{title}</h3>
      <p className="mb-3 mt-1 text-[11px] text-ink/35">Original model output · read-only{source === 'legacy' ? ' · earlier prompt version' : ''}</p>
      {children}
    </section>
  );
}

function Card({ evidence, kind, title, seconds, onSeek, children }: { evidence: StructuredEntity['evidence']; kind: 'entity' | 'instrument' | 'asset'; title: string; seconds: number | null; onSeek: (seconds: number) => void; children: ReactNode }) {
  const at = seconds ?? evidence?.timestampSeconds ?? null;
  return (
    <article className="w-64 max-w-full overflow-hidden rounded-2xl border border-ink/10 bg-white text-xs" data-testid="evidence-card">
      <button aria-label={at === null ? `${title} image` : `Play video from ${formatClock(at)}: ${title}`} className="block w-full disabled:cursor-default" disabled={at === null} onClick={() => at !== null && onSeek(at)} type="button">
        <EvidenceFrame aspect={2} className="!rounded-none" kind={kind} label={title} seconds={at} src={evidence?.imageUrl} />
      </button>
      <div className="space-y-1 p-3"><h4 className="text-sm font-semibold">{title}</h4>{children}{at !== null && <p className="text-ink/50">Most visible at <b className="font-mono">{formatClock(at)}</b></p>}</div>
    </article>
  );
}

function EntityCard({ entity, holds, onSeek }: { entity: StructuredEntity; holds: string[]; onSeek: (seconds: number) => void }) {
  const span = entity.firstSeenSeconds !== null && entity.lastSeenSeconds !== null ? `${formatClock(entity.firstSeenSeconds)}–${formatClock(entity.lastSeenSeconds)}` : null;
  return (
    <Card evidence={entity.evidence} kind="entity" onSeek={onSeek} seconds={entity.timestampSeconds} title={entity.label || entity.type}>
      <p className="text-ink/60">{entity.description}</p>
      {holds.length > 0 && <p>Holds <b>{holds.join(', ')}</b></p>}
      {span && <p className="text-ink/50">On screen {span}</p>}
    </Card>
  );
}

function InstrumentCard({ instrument, holder, onSeek }: { instrument: StructuredInstrument; holder?: string; onSeek: (seconds: number) => void }) {
  return (
    <Card evidence={instrument.evidence} kind="instrument" onSeek={onSeek} seconds={instrument.timestampSeconds} title={instrument.name}>
      <p className="text-ink/60">{instrument.description}</p>
      <p className="text-ink/50">Threat {instrument.threatLevel ?? 'unrated'}{instrument.threatLevel !== null ? '/5' : ''}</p>
      <p>Held by <b>{holder ?? 'unknown'}</b></p>
    </Card>
  );
}
